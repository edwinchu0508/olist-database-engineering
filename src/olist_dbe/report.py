"""Markdown data-quality report for one load, built only from what the database recorded."""
import psycopg


def latest_load_id(conn: psycopg.Connection) -> int | None:
    row = conn.execute("SELECT max(load_id) FROM meta.load_runs WHERE status <> 'running'").fetchone()
    return row[0]


def render_dq_report(conn: psycopg.Connection, load_id: int) -> str:
    run = conn.execute(
        "SELECT status, data_dir, started_at, finished_at, error FROM meta.load_runs WHERE load_id = %s",
        (load_id,),
    ).fetchone()
    if run is None:
        raise ValueError(f"no load with id {load_id}")
    status, data_dir, started_at, finished_at, error = run
    server = conn.execute("SHOW server_version").fetchone()[0]

    lines = [
        "# Data quality report",
        "",
        "Generated by `olist-dbe dq-report` from `meta.load_runs`, `meta.load_files` and `dq.check_results`.",
        "Every number below was measured by the check SQL in `sql/dq/`; nothing is typed in by hand.",
        "",
        f"- Load: #{load_id}, **{status}**, started {started_at:%Y-%m-%d %H:%M:%S %Z}"
        + (f", finished {finished_at:%H:%M:%S}" if finished_at else ""),
        f"- PostgreSQL {server}",
    ]
    if error:
        lines.append(f"- Error: `{error}`")

    lines += ["", "## Source files", "", "| File | Rows loaded | Bytes | SHA-256 | Reference |", "|---|---:|---:|---|---|"]
    for file_name, rows, size, sha256, matches in conn.execute(
        "SELECT file_name, rows_loaded, bytes, sha256, matches_reference FROM meta.load_files"
        " WHERE load_id = %s ORDER BY file_name",
        (load_id,),
    ):
        reference = {True: "match", False: "**differs**", None: "-"}[matches]
        lines.append(f"| {file_name} | {_n(rows)} | {_n(size)} | `{sha256[:12]}…` | {reference} |")

    for severity, title, intro in (
        ("blocking", "Blocking checks",
         "Preconditions of the publish. Any violation stops the load before core is touched."),
        ("warning", "Warnings",
         "Known anomalies of the source data. The rows are kept; analyses must account for them."),
    ):
        lines += ["", f"## {title}", "", intro, "", "| Check | Status | Violations | ms |", "|---|---|---:|---:|"]
        for name, check_status, violations, duration in conn.execute(
            "SELECT check_name, status, violations, duration_ms FROM dq.check_results"
            " WHERE load_id = %s AND severity = %s ORDER BY check_name",
            (load_id, severity),
        ):
            lines.append(f"| `{name}` | {check_status} | {_n(violations)} | {duration} |")
    lines.append("")
    return "\n".join(lines)


def _n(value: int | None) -> str:
    return "-" if value is None else f"{value:,}"
