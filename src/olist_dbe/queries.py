"""Business queries (sql/queries/*.sql): parameters, execution and result fingerprints.

Each file holds one query. Its parameters are psql variables (:'name'), so the file runs unchanged
in psql (`psql -v name=value -f file`). The values behind the published results are declared in the
file's header as `-- @param name = value`; render() substitutes them as SQL literals.

A result's fingerprint is a SHA-256 over its column names and rows in query order (every query has a
total ORDER BY). Numbers are compared by value, so 12.30 and 12.3 hash alike: a rewrite that keeps
the result but changes a numeric scale still matches.
"""
import csv
import datetime
import decimal
import hashlib
import re
import uuid
from dataclasses import dataclass
from pathlib import Path

import psycopg
from psycopg import sql

from . import config, provenance

QUERY_DIR = config.SQL_DIR / "queries"
_PARAM = re.compile(r"^--\s*@param\s+(\w+)\s*=\s*(.*?)\s*$", re.MULTILINE)
_VARIABLE = re.compile(r"(?<!:):'(\w+)'")


@dataclass(frozen=True)
class Query:
    name: str
    path: Path
    text: str
    params: dict[str, str]

    @property
    def title(self) -> str:
        """The first comment line, without its leading '-- '."""
        return self.text.splitlines()[0].removeprefix("--").strip()


def load(path: Path) -> Query:
    text = path.read_text(encoding="utf-8")
    return Query(path.stem, path, text, dict(_PARAM.findall(text)))


def all_queries() -> list[Query]:
    return [load(path) for path in sorted(QUERY_DIR.glob("q*.sql"))]


def render(conn: psycopg.Connection, text: str, params: dict[str, object]) -> str:
    """`text` with each :'name' replaced by params[name] as an SQL literal."""
    used = set(_VARIABLE.findall(text))
    missing = used - set(params)
    if missing:
        raise ValueError(f"no value for {', '.join(sorted(missing))}")
    return _VARIABLE.sub(lambda m: sql.Literal(str(params[m.group(1)])).as_string(conn), text)


def execute(conn: psycopg.Connection, text: str, params: dict[str, object]) -> tuple[list[str], list[tuple]]:
    """Run one query with literal parameters; returns (column names, rows)."""
    with conn.cursor() as cur:
        cur.execute(render(conn, text, params))
        return [c.name for c in cur.description], cur.fetchall()


def canonical(value: object) -> str:
    if value is None:
        return "\\N"
    if isinstance(value, decimal.Decimal):
        return format(value.normalize(), "f")
    if isinstance(value, float):
        return repr(value)
    if isinstance(value, uuid.UUID):
        return value.hex
    if isinstance(value, (datetime.date, datetime.datetime)):
        return value.isoformat()
    return str(value)


def fingerprint(columns: list[str], rows: list[tuple]) -> str:
    digest = hashlib.sha256("\t".join(columns).encode() + b"\n")
    for row in rows:
        digest.update("\t".join(canonical(v) for v in row).encode() + b"\n")
    return digest.hexdigest()


def write_csv(path: Path, columns: list[str], rows: list[tuple]) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, lineterminator="\n")
        writer.writerow(columns)
        writer.writerows(["" if v is None else str(v) for v in row] for row in rows)


PREVIEW_ROWS = 12


def write_results(conn: psycopg.Connection, out_dir: Path) -> list[tuple[Query, int, str]]:
    """Run every query with its declared parameters; write <name>.csv and README.md to out_dir."""
    out_dir.mkdir(parents=True, exist_ok=True)
    data = provenance.loaded_data(conn)
    load_id, finished, files_match = data["load_id"], data["finished"], data["files_match_reference"]
    version = conn.execute("SELECT current_setting('server_version')").fetchone()[0]
    lines = [
        "# Query results",
        "",
        "Generated by `olist-dbe queries --out docs/query_results` from the database it verified; definitions in",
        "[docs/queries.md](../queries.md), SQL in [sql/queries/](../../sql/queries/). Each CSV holds the full result.",
        "",
        f"- PostgreSQL {version}, database `{conn.info.dbname}`, data from load {load_id} ({finished:%Y-%m-%d %H:%M}),"
        f" source files {'matching' if files_match else '**not matching**'} `data_manifest.json`",
        "- Fingerprint: SHA-256 over the column names and rows in query order (numbers by value)",
        "",
    ]
    summary = []
    for query in all_queries():
        columns, rows = execute(conn, query.text, query.params)
        digest = fingerprint(columns, rows)
        write_csv(out_dir / f"{query.name}.csv", columns, rows)
        summary.append((query, len(rows), digest))
        params = ", ".join(f"`{k} = {v}`" for k, v in query.params.items()) or "none"
        lines += [
            f"## {query.title}",
            "",
            f"[{query.name}.csv]({query.name}.csv): {len(rows):,} rows. Parameters: {params}.",
            f"Fingerprint `{digest[:16]}`.",
            "",
            "| " + " | ".join(columns) + " |",
            "|" + "---|" * len(columns),
        ]
        shown = rows if len(rows) <= PREVIEW_ROWS + 3 else rows[:PREVIEW_ROWS]
        lines += ["| " + " | ".join("" if v is None else str(v) for v in row) + " |" for row in shown]
        if len(shown) < len(rows):
            lines.append(f"| … {len(rows) - len(shown):,} more rows in the CSV |" + " |" * (len(columns) - 1))
        lines.append("")
    (out_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")
    return summary
